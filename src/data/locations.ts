/* ──────────────────────────── 列表构造（官方 `PSl` / `TSl` 的 useMemo 逐条对应）──────────────────────────── */

export interface LocationOption {
  /** 落进资料的值 = **英文名**（官方 `onChange(m.englishName)` / `onChange(x.name)`）*/
  value: string;
  /** 显示出来的 = **本地化名** */
  label: string;
  /** 仅国家有：ISO alpha-2（官方 item 的 value 里拼了它，所以搜 "CN" 也能命中）*/
  code?: string;
}

const COUNTRY_TABLES: Record<LocationLocale, Record<string, string>> = {
  en: COUNTRY_NAMES_EN,
  zh: COUNTRY_NAMES_ZH,
  ja: COUNTRY_NAMES_JA,
  ko: COUNTRY_NAMES_KO,
};

/**
 * `countryOptions(locale)` —— 官方 `PSl`：
 * ```js
 * const m = ku.getNames('en',{select:'official'}), k = ku.getNames(u,{select:'official'});
 * Object.entries(m).map(([b,_]) => ({iso2:b, englishName:_, localizedName:k[b]||_}))
 *   .sort((a,b) => a.localizedName.localeCompare(b.localizedName, u, {sensitivity:'base'}))
 * ```
 * ⚠️ 官方 `englishName` 用的是**这份表的原文**（en 表里有 5 条 ISO 官方名自带逗号，
 *    例如 `People's Republic of China,China`）—— 逐字搬过来，不做"美化" ✗
 */
export function countryOptions(locale: LocationLocale): LocationOption[] {
  const local = COUNTRY_TABLES[locale];
  return Object.keys(COUNTRY_NAMES_EN)
    .map((iso2) => {
      const englishName = COUNTRY_NAMES_EN[iso2];
      return { value: englishName, label: local[iso2] || englishName, code: iso2 };
    })
    .sort((a, b) => a.label.localeCompare(b.label, locale, { sensitivity: 'base' }));
}

/** 英文名 → ISO alpha-2（对应官方 `ku.getAlpha2Code(country,'en')`）*/
export function countryCodeOf(englishName?: string): string | undefined {
  if (!englishName) return undefined;
  const want = englishName.trim().toLowerCase();
  for (const iso2 of Object.keys(COUNTRY_NAMES_EN)) {
    if (COUNTRY_NAMES_EN[iso2].toLowerCase() === want) return iso2;
  }
  return undefined;
}

/**
 * `cityOptions(locale, country)` —— 官方 `TSl`：
 * 选了国家就只出该国的城市（`r9t.filter(c => c.countryCode === m)`），
 * 再按本地化名排序（`SSl` 里没有的城市直接用英文名）。
 */
export function cityOptions(locale: LocationLocale, countryEnglishName?: string): LocationOption[] {
  const code = countryCodeOf(countryEnglishName);
  const list = code ? OFFICIAL_CITIES.filter((city) => city.countryCode === code) : OFFICIAL_CITIES;
  return list
    .map((city) => ({
      value: city.name,
      label: (locale === 'en' ? undefined : CITY_NAMES[city.name]?.[locale]) || city.name,
    }))
    .sort((a, b) => a.label.localeCompare(b.label, locale, { sensitivity: 'base' }));
}
